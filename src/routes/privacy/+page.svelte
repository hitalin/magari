	<p class="label">まがり</p>
	<h1>プライバシーポリシー</h1>
	<p class="doc-lead">まがりが何を預かり、何に使うかを書きます。預かる情報は、できるだけ少なくしています。</p>

	<h2>1. 預かるもの</h2>
	<ul>
		<li><strong>ログインしたアカウントの情報</strong>: X または Misskey の ID、表示名、アイコンの画像の場所。メールアドレスとパスワードは預かりません。</li>
		<li><strong>ログインを保つための情報</strong>: X や Misskey から受け取る認証用の情報、ログイン中であることを示す情報、ログインしたときの IP アドレスとブラウザの種類、パスキーを作った場合はその公開鍵。</li>
		<li><strong>載せた内容</strong>: 間（会）、ページ、画像。これらは公開されます。</li>
		<li><strong>運営への連絡</strong>: 連絡フォームに書かれた名前、返信先、本文。</li>
	</ul>
	<p>見るだけなら、ログインは要らず、上のどれも預かりません。</p>

	<h2>2. 使いみち</h2>
	<p>ログインの確認、載せた内容の表示、連絡への返事、荒らしや不正な利用への対応のためにだけ使います。</p>

	<h2>3. 外に出すとき</h2>
	<p>預かった情報を売ったり、広告のために渡したりしません。法令に基づく手続き（裁判所の命令など）があった場合は、それに従います。</p>

	<h2>4. 使っている外のサービス</h2>
	<ul>
		<li><strong>Cloudflare</strong>: まがりの配信とデータの保存に使っています。日本の外にあるサーバーに置かれることがあります。アクセスの数を知るために Cloudflare の計測を使うことがあります（Cookie を使わず、個人を見分けません）。</li>
		<li><strong>X、Misskey</strong>: ログインのためにだけ使います。まがりがあなたの代わりに投稿することはありません。</li>
		<li><strong>通知</strong>: 運営への連絡が届いたことを運営者に知らせるために、外の通知サービスを使うことがあります。送るのは連絡の種別と対象のページだけで、名前・返信先・本文は送りません。</li>
		<li><strong>Google マップ</strong>: 地図はリンクを置いているだけで、まがりから Google に情報を送ることはありません。</li>
	</ul>

	<h2>5. Cookie</h2>
	<p>ログインを保つためにだけ使います。広告や追跡のための Cookie は使いません。</p>

	<h2>6. 消すとき</h2>
	<p>アカウントは、自分のページからいつでも消せます。消すと、アカウントの情報、自分で開いた間、自分のページが消えます。運営への連絡は、対応の記録として残し、要らなくなったら消します。自分の情報を見たい、直したい、消したいときは<a href="/contact?kind=other">運営に連絡</a>してください。</p>

	<h2>7. 自分で載せていないページについて</h2>
	<p>管理する人のいないハコや団体のページは、名前と公式へのリンクだけを載せ、「非公式」と表示しています。取り下げや引き取りは<a href="/contact">運営への連絡</a>から申し出てください。</p>

