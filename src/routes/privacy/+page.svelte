	<h1>プライバシーポリシー</h1>
	<p class="doc-lead">まがりが預かる情報と、その使いみちです。預かるのは、動かすのに要るものだけです。</p>

	<h2>1. 預かるもの</h2>
	<ul>
		<li><strong>アカウント</strong>: X または Misskey の ID、表示名、アイコン画像の URL。メールアドレスとパスワードは預かりません。</li>
		<li><strong>ログインの維持</strong>: X から受け取る認証用の情報、ログイン状態、ログイン時の IP アドレスとブラウザの種類、パスキーの公開鍵（作った場合）。</li>
		<li><strong>載せた内容</strong>: 間（会）、ページ、画像。公開されます。</li>
		<li><strong>主催どうしの関係のメモ</strong>: ページの管理者が書く、共演できない組み合わせなどの覚え書き。相手にできるのは、主催として載っているページだけです。書いたページの管理者だけが見られ、公開されません。</li>
		<li><strong>運営への連絡</strong>: 名前、返信先、本文。</li>
	</ul>
	<p>見るだけなら、どれも預かりません。</p>

	<h2>2. 使いみち</h2>
	<p>ログインの確認、載せた内容の表示、連絡への返事、不正な利用への対応。これ以外には使いません。</p>

	<h2>3. 外に出すとき</h2>
	<p>売りません。広告のために渡しません。法令に基づく手続き（裁判所の命令など）には従います。</p>

	<h2>4. 使っている外のサービス</h2>
	<ul>
		<li><strong>Cloudflare</strong>: 配信と保存に使います。データは日本の外に置かれることがあります。アクセス数の計測は Cookie を使わず、個人を見分けません。</li>
		<li><strong>X、Misskey</strong>: ログインに使います。つないだアカウントの ID は、あなたのページに出ます（2 つ以上つないでいれば、「自分」のページで外せます）。Misskey の認証用の情報は、本人の確認のあと保存しません。あなたの代わりに投稿することはありません。</li>
		<li><strong>通知</strong>: 連絡が届いたことを運営者に知らせるために使います。送るのは連絡の種別と対象のページだけで、名前・返信先・本文は送りません。</li>
		<li><strong>Google マップ</strong>: リンクを置いているだけです。まがりから Google に情報は送りません。</li>
	</ul>

	<h2>5. Cookie</h2>
	<p>ログインの維持にだけ使います。広告や追跡には使いません。</p>

	<h2>6. 消すとき</h2>
	<p>アカウントは「自分」のページからいつでも消せます。アカウントの情報、自分で開いた間、自分のページが消えます。運営への連絡は対応の記録として残し、要らなくなったら消します。自分の情報を見たい、直したい、消したいときは<a href="/contact?kind=other">運営に連絡</a>してください。</p>

	<h2>7. 自分で載せていないページ</h2>
	<p>管理者のいないハコや団体のページは、名前・エリア・公式へのリンク・公式ページにある店の写真だけを載せ、「非公式」と表示します。取り下げと引き取りは<a href="/contact">運営への連絡</a>から申し出てください。</p>

