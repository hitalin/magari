	<h1>会を開く方へ</h1>
	<p class="doc-lead">まがりは、あちこちの店で開かれる会を一か所で見られるようにするサイトです。個人が無償で動かしていて、広告はありません。あなたの会が、お声がけする前から載っていることがあります。</p>

	<h2>なぜ載っているか</h2>
	<p>あなたが申し込んだ店が、予定表を公開しているからです。まがりはその予定表を 1 時間ごとに写しています。あなたの X やほかの告知を、まがりが集めて回ることはありません。</p>

	<h2>載せているもの</h2>
	<ul>
		<li>題・日時・場所・説明の冒頭 120 字。全文は載せず、元の告知へリンクします。</li>
		<li>フライヤーなどの画像は写しません。</li>
		<li>あなたの名前のページは作りません。題に名前があれば、題としてそのまま出ます。</li>
		<li>検索エンジンに載せないよう指定しています。</li>
	</ul>
	<p>会のページには、予定表から写した情報で、本人が載せたものではないと表示しています。参加の受付やお金のやり取りは、まがりではしません。</p>

	<h2>直したいとき</h2>
	<p>店の予定表を直してもらってください。1 時間ほどでまがりにも反映されます。中止や削除も同じです。まがりの側では直せません。</p>

	<h2>載せたくないとき</h2>
	<p>会のページの下にある「運営に連絡」から一言ください。ログインは要りません。その会を非表示にします。</p>
	<p>この先の会も載せたくないときは、そう書いてください。題に入るあなたの名前や会の名前を控えて、以後は写しません。すでに写した先の会も消えます。</p>

	<h2>店が載せた会</h2>
	<p>店（ハコ）の管理者が、その店で開かれる会を載せることもあります。もう告知が出ている会だけで、載せるのは題・日時・店と、あなたの告知へのリンクだけです。会のページには、店が載せた情報で、本人が載せたものではないと表示しています。直したいときや外したいときは、店に伝えるか、会のページの下の「運営に連絡」から一言ください。</p>

	<h2>自分で載せたいとき</h2>
	<p>X か Misskey でログインすると、自分の会を自分で載せられます。フライヤーを付けられ、開いてきた会が自分のページに残ります。店の予定表から写した同じ会と二つ並ぶときは、<a href="/contact?kind=other">運営への連絡</a>から知らせてください。写したほうを非表示にします。</p>

