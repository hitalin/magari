	<h1>掲載と削除の方針</h1>
	<p class="doc-lead">まがりに何が載るかと、問題があったときの対応です。</p>

	<h2>1. 載るもの</h2>
	<p>利用者が自分で載せた間（会）とページです。載せた時点で公開され、運営者は事前に中身を確かめません。載せられないものは<a href="/terms">利用規約</a>のとおりです。</p>
	<p>ほかに、店が公開している予定表から運営者が写した間があります。写すのは題・日時・場所・元の告知へのリンク・説明の冒頭だけで、間のページにその旨を表示します。</p>

	<h2>2. 非公式のページ</h2>
	<p>管理者のいないハコや団体のページは、名前・エリア・公式へのリンク・公式ページにある店の写真だけを載せ、「非公式」と表示します。紹介文は載せません。</p>

	<h2>3. 取り下げと引き取り</h2>
	<p>載せられた側（店、主催者、権利者、本人）は、いつでも取り下げを申し出られます。ハコや団体の方は、ページを引き取って自分で管理することもできます。どちらも<a href="/contact">運営への連絡</a>から。ログインは要りません。次の 3 つを書いてください。</p>
	<ul>
		<li>対象のページや会（@ID か URL）</li>
		<li>あなたと対象の関係と、それが分かるもの（公式サイト、SNS のアカウントなど）</li>
		<li>何が問題か（引き取りなら不要）</li>
	</ul>

	<h2>4. 対応の順</h2>
	<ol>
		<li><strong>非表示にします。</strong> 気づき次第、数日以内を目安に、対象を公開から外します。この時点では消しません。</li>
		<li><strong>確かめます。</strong> 申し出の内容と、必要なら載せた人の話を確かめます。</li>
		<li><strong>決めます。</strong> 消す、元に戻す、直してもらう、のどれかです。取り下げたページの ID は、以後だれも使えません。</li>
	</ol>
	<p>引き取りは、そのハコや団体の方だと確かめられたら、ページの管理をお渡しします。</p>
	<p>運営者は個人で、すぐに気づけないことがあります。急ぐときは、その旨を書いてください。</p>

	<h2>5. 載せた人へ</h2>
	<p>運営者が非表示にしたページや会には、載せた本人にだけ、その旨を表示します。異議は<a href="/contact?kind=other">運営への連絡</a>から知らせてください。</p>

	<h2>6. 記録</h2>
	<p>申し出の日時と、対応の日時・内容を記録します。</p>

	<h2>7. 載せた人の情報</h2>
	<p>載せた人がだれかを、運営者の判断で申し出た人に伝えることはありません。法律に基づく開示の手続きには従います。</p>

