	<h1>掲載と削除の方針</h1>
	<p class="doc-lead">まがりに何が載るか、載っているものに問題があったときにどうするかを書きます。</p>

	<h2>1. 載るもの</h2>
	<p>まがりに載るのは、利用者が自分で載せた間（会）とページです。載せるとすぐ公開され、運営者が前もって中身を確かめることはありません。載せてはいけないものは<a href="/terms">利用規約</a>に書いています。</p>

	<h2>2. 非公式のページ</h2>
	<p>管理する人のいないハコや団体のページは、名前・エリア・公式へのリンクだけを載せ、「非公式」と表示します。写真や紹介文は載せません。そのハコや団体の方は、ページを引き取って自分で管理することも、取り下げることもできます。</p>

	<h2>3. 取り下げの申し出</h2>
	<p>載っている内容に問題があるとき（権利を侵している、事実と違う、載せてほしくない、など）は、<a href="/contact">運営への連絡</a>から申し出てください。ログインは要りません。次のことを書いてもらえると早く対応できます。</p>
	<ul>
		<li>対象のページや会（@ID か URL）</li>
		<li>あなたと対象の関係（ハコの運営者、主催者、写真の権利者、載せられた本人など）と、それが分かるもの（公式サイトや SNS のアカウントなど）</li>
		<li>何が問題か</li>
	</ul>

	<h2>4. 対応の進め方</h2>
	<ol>
		<li><strong>まず非表示にします。</strong> 申し出に気づいたら、できるだけ早く（数日以内を目安に）、対象を公開から外します。この時点では消しません。</li>
		<li><strong>確かめます。</strong> 申し出の内容と、必要なら載せた人の話を確かめます。</li>
		<li><strong>決めます。</strong> 消す、元に戻す、内容を直してもらう、のどれかにします。取り下げたページの ID は、以後だれも使えないようにします。</li>
	</ol>
	<p>運営者は個人で、すぐに気づけないことがあります。急ぐときは、連絡にその旨を書いてください。</p>

	<h2>5. 載せた人へ</h2>
	<p>運営者が非表示にしたページや会には、載せた本人にだけ見える形でその旨を表示します。心当たりが無いとき、納得できないときは、同じく<a href="/contact?kind=other">運営への連絡</a>から知らせてください。</p>

	<h2>6. 記録</h2>
	<p>申し出を受けた日時と、対応した日時・内容を記録します。</p>

	<h2>7. 載せた人の情報の開示</h2>
	<p>載せた人がだれかを、申し出た人に運営者の判断で伝えることはありません。法律に基づく開示の手続きがあった場合は、それに従います。</p>

