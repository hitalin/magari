	<p class="label">◱</p>
	<h1>お店・団体の方へ</h1>
	<p class="doc-lead">まがりは、あちこちの店で開かれる会を一か所で見られるようにするサイトです。個人が無償で動かしていて、広告はありません。あなたの店の予定が、お声がけする前から載っていることがあります。</p>

	<h2>載せているもの</h2>
	<ul>
		<li><strong>予定</strong>: 店が公開している予定表から、題・日時・場所・説明の冒頭 120 字。全文は載せず、元の告知へリンクします。</li>
		<li><strong>店のページ</strong>: 名前・エリア・公式へのリンク・公式ページの店の写真・X のアイコン。「非公式」と表示し、紹介文は載せません。</li>
	</ul>
	<p>どちらも、検索エンジンに載せないよう指定しています。店の名前で検索した人には、公式のページを見てもらいます。</p>

	<h2>店がすること</h2>
	<p>ありません。いまの予定表をそのまま使ってください。まがりが 1 時間ごとに写すので、変更や中止もそのまま反映されます。</p>

	<h2>載せたくないとき</h2>
	<p><a href="/contact?kind=takedown">運営への連絡</a>から一言ください。ログインは要りません。まず非表示にし、以後は写しません。</p>

	<h2>自分のページにしたいとき</h2>
	<p>店の X アカウントでログインして、店のページの「ページの引き取り」を押すと、その場で管理が移ります。運営者とのやり取りは要りません。</p>
	<ul>
		<li>「非公式」の表示が外れ、検索にも載ります。</li>
		<li>紹介文・写真・営業時間・行き方を自分で書けます。</li>
		<li>「ここで開けたい人」の声かけ先として、店の X が出ます。</li>
		<li>予定は、いまの予定表から写し続けます。</li>
	</ul>
	<p>店の X を使えないときは、<a href="/contact?kind=claim">運営への連絡</a>から知らせてください。</p>

