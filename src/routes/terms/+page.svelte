	<h1>利用規約</h1>
	<p class="doc-lead">まがり（magari.cc）を使うときの約束です。ページを作る、間を開く（会を載せる）ときは、この規約に同意したものとします。</p>

	<h2>1. まがりについて</h2>
	<p>まがりは、間（会や催し）とハコ（場所）の情報を、利用者が自分で載せるための場所です。個人が無償で運営しています。</p>

	<h2>2. 運営者は当事者ではありません</h2>
	<p>運営者は、載っている会の主催者でも、場所の貸し主・借り主でもありません。会への参加、出店、場所の貸し借り、お金のやり取りは、当事者どうしで行ってください。運営者はそれらを仲介せず、その結果に関わりません。</p>

	<h2>3. 載せる人の責任</h2>
	<p>載せた内容（題、説明、画像、リンクなど）が正しいこと、それを載せる権利があることは、載せた人が責任を持ちます。次のものは載せないでください。</p>
	<ul>
		<li>他人の写真・フライヤー・文章などを、権利を持たずに写したもの</li>
		<li>他人の個人情報や、本人が公開していない事柄（病気や障害、所属、住所など）</li>
		<li>主催者本人でない人が、個人を主催者として載せること</li>
		<li>嘘の会、なりすまし、嫌がらせ、宣伝だけが目的のもの</li>
		<li>法令や公序良俗に反するもの</li>
	</ul>

	<h2>4. 運営者ができること</h2>
	<p>この規約に反するもの、申し出があったもの、そのほか運営者が適切でないと判断したものは、予告なく非表示にしたり、消したりすることがあります。くり返す場合は、アカウントの利用を止めることがあります。進め方は<a href="/policy">掲載と削除の方針</a>に書いています。</p>

	<h2>5. 保証しないこと</h2>
	<p>載っている情報が正しいこと、会が実際に開かれること、まがりが止まらないこと、データが失われないことを、運営者は保証しません。出かける前に、主催者の告知で確かめてください。</p>
	<p>まがりを使ったこと、使えなかったことで生じた損害について、運営者は、故意または重大な過失がある場合を除いて責任を負いません。</p>

	<h2>6. 載せた内容の扱い</h2>
	<p>載せた内容の権利は、載せた人に残ります。運営者は、まがりの中で表示するため、また共有しやすい形（リンクカード、カレンダー形式など）で配るために、その内容を無償で使えるものとします。</p>

	<h2>7. やめるとき</h2>
	<p>アカウントは、自分のページからいつでも消せます。消すと、自分で開いた間と自分のページも消えます。</p>

