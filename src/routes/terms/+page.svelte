	<h1>利用規約</h1>
	<p class="doc-lead">まがり（magari.cc）を使う約束です。ページを作るか、間（会）を載せた時点で、同意したものとします。</p>

	<h2>1. まがりとは</h2>
	<p>間（会）とハコ（場所）の情報を、利用者が自分で載せる場所です。個人が無償で運営しています。</p>

	<h2>2. 運営者は当事者ではありません</h2>
	<p>運営者は、会の主催者でも、場所の貸し主・借り主でもありません。参加、出店、貸し借り、お金のやり取りは当事者どうしで行ってください。運営者は仲介せず、結果に関わりません。</p>

	<h2>3. 載せる人の責任</h2>
	<p>載せた内容が正しいことと、それを載せる権利があることは、載せた人の責任です。次のものは載せられません。</p>
	<ul>
		<li>権利を持たない他人の写真・フライヤー・文章</li>
		<li>他人の個人情報や、本人が公開していない事柄（病気、障害、所属、住所など）</li>
		<li>本人でない人が、個人を主催者として載せること</li>
		<li>嘘の会、なりすまし、嫌がらせ、宣伝だけが目的のもの</li>
		<li>法令や公序良俗に反するもの</li>
	</ul>

	<h2>4. 運営者ができること</h2>
	<p>規約に反するもの、申し出があったもの、運営者が不適切と判断したものは、予告なく非表示にするか、消します。くり返す人のアカウントは止めます。手順は<a href="/policy">掲載と削除の方針</a>のとおりです。</p>

	<h2>5. 保証しないこと</h2>
	<p>情報が正しいこと、会が開かれること、まがりが止まらないこと、データが残ることを、運営者は保証しません。行く前に、主催者の告知で確かめてください。</p>
	<p>まがりを使ったこと、使えなかったことによる損害について、運営者は、故意または重大な過失がある場合を除き、責任を負いません。</p>

	<h2>6. 載せた内容の扱い</h2>
	<p>権利は載せた人に残ります。運営者は、まがりでの表示と、共有用の形（リンクカード、カレンダー形式など）での配布に、その内容を無償で使えます。</p>

	<h2>7. やめるとき</h2>
	<p>アカウントは「自分」のページからいつでも消せます。自分で開いた間と、自分のページも消えます。</p>

	<h2>8. 規約を変えるとき</h2>
